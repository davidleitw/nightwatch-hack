def database_path() -> Path:
    """Return the configured SQLite path and fail clearly for bad configuration."""
    configured = os.getenv("DB_PATH", DEFAULT_DB_PATH).strip()
    if not configured:
        raise RuntimeError("DB_PATH must point to a SQLite database file")
    return Path(configured)


@contextmanager
def connect():
    path = database_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    db = sqlite3.connect(path, timeout=10)
    try:
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA foreign_keys = ON")
        # sqlite3.Connection commits or rolls back on exit, but does not close
        # itself. Keep both responsibilities explicit at every call site.
        with db:
            yield db
    finally:
        db.close()


def init_db() -> None:
    """Run the one-time schema migration in one SQLite transaction."""
    with connect() as db:
        db.execute("BEGIN IMMEDIATE")
        db.execute(CREATE_MIGRATIONS_TABLE)
        # CREATE IF NOT EXISTS leaves an existing orders table and its payloads
        # untouched while upgrading databases created by the first API version.
        db.execute(CREATE_ORDERS_TABLE)
        db.execute(CREATE_PRODUCTS_TABLE)
        db.execute(CREATE_CARTS_TABLE)
        db.execute(CREATE_CART_ITEMS_TABLE)

        migrated = db.execute(
            "SELECT 1 FROM schema_migrations WHERE version = 1"
        ).fetchone()
        if migrated is None:
            for product in SEED_PRODUCTS:
                db.execute(
                    """
                    INSERT INTO products
                        (name, category, price, icon, color, description)
                    VALUES (?, ?, ?, ?, ?, ?)
                    """,
                    tuple(product[field] for field in PRODUCT_FIELDS),
                )
            db.execute("INSERT INTO schema_migrations (version) VALUES (1)")


