def _product_payload(row: sqlite3.Row) -> dict:
    return {field: row[field] for field in ("id", *PRODUCT_FIELDS)}


def _find_product(db: sqlite3.Connection, product_id: int) -> sqlite3.Row | None:
    return db.execute(
        f"SELECT {PRODUCT_SELECT} FROM products WHERE id = ?",
        (product_id,),
    ).fetchone()


def _require_cart(db: sqlite3.Connection, cart_id: str) -> None:
    if db.execute("SELECT 1 FROM carts WHERE id = ?", (cart_id,)).fetchone() is None:
        raise HTTPException(status_code=404, detail="購物車不存在。")


def _cart_items(db: sqlite3.Connection, cart_id: str) -> list[dict]:
    rows = db.execute(
        """
        SELECT p.id, p.name, p.category, p.price, p.icon, p.color,
               p.description, ci.product_id, ci.quantity,
               p.price * ci.quantity AS line_total
          FROM cart_items AS ci
          JOIN products AS p ON p.id = ci.product_id
         WHERE ci.cart_id = ?
         ORDER BY ci.product_id
        """,
        (cart_id,),
    ).fetchall()
    items = []
    for row in rows:
        item = _product_payload(row)
        item.update(
            product_id=row["product_id"],
            quantity=row["quantity"],
            line_total=row["line_total"],
        )
        items.append(item)
    return items


def _cart_payload(db: sqlite3.Connection, cart_id: str) -> dict:
    _require_cart(db, cart_id)
    items = _cart_items(db, cart_id)
    return {
        "id": cart_id,
        "items": items,
        "total": sum(item["line_total"] for item in items),
    }


def _new_order(lines: list[dict]) -> dict:
    return {
        "id": uuid4().hex,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "total": sum(line["price"] * line["quantity"] for line in lines),
        "items": lines,
    }


def _insert_order(
    db: sqlite3.Connection,
    order: dict,
    name: str,
    address: str,
) -> None:
    payload = {**order, "name": name, "address": address}
    db.execute(
        "INSERT INTO orders (id, created_at, payload) VALUES (?, ?, ?)",
        (
            order["id"],
            order["created_at"],
            json.dumps(payload, ensure_ascii=False),
        ),
    )


def _order_lines_from_items(
    db: sqlite3.Connection,
    items: list[Item],
) -> list[dict]:
    quantities: dict[int, int] = {}
    product_rows: dict[int, sqlite3.Row] = {}
    for item in items:
        row = product_rows.get(item.product_id)
        if row is None:
            row = _find_product(db, item.product_id)
            if row is None:
                # Keep the original orders endpoint's 400 behavior.
                raise HTTPException(status_code=400, detail="商品不存在，請重新整理商品列表。")
            product_rows[item.product_id] = row
        quantity = quantities.get(item.product_id, 0) + item.quantity
        if quantity > MAX_QUANTITY:
            raise HTTPException(status_code=400, detail="每件商品最多可購買 99 件。")
        quantities[item.product_id] = quantity

    return [
        {
            "product_id": product_id,
            "name": product_rows[product_id]["name"],
            "price": product_rows[product_id]["price"],
            "quantity": quantity,
        }
        for product_id, quantity in quantities.items()
    ]


